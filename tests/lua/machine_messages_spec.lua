-- steam-machine: OnWsMessage / HandleModule routing of System Bridge pushes into C4 variables/events
local H = require ('c4_mock')

local function online ()
	local env = H.machine ()
	env.goOnline ()
	return env
end

local function push (env, module, data)
	env.rx ({ type = 'DATA_UPDATE', module = module, data = data })
end

local function eventsFired (env)
	local out = {}
	for _, a in ipairs (env.c4.of ('FireEvent')) do out [#out + 1] = a [1] end
	return out
end

describe ('OnWsMessage envelope handling', function ()
	it ('ignores undecodable and non-object messages without changing state', function ()
		local env = H.machine ()
		env.boot ('192.168.1.50')
		env.g_ws:establish ()
		env.g_ws:emit ('this is not json {')
		env.g_ws:emit ('42')
		env.g_ws:emit ('"just a string"')
		check.falsy (env.g_online)
	end)

	it ('any non-error message proves the token is good (goes online once)', function ()
		local env = H.machine ()
		env.boot ('192.168.1.50')
		env.setProperty ('System Bridge Token', 'tk')
		env.g_ws:establish ()
		env.rx ({ type = 'DATA_UPDATE', module = 'cpu', data = {} })
		env.rx ({ type = 'DATA_UPDATE', module = 'cpu', data = {} })
		check.truthy (env.g_online)
		check.eq (env.Variables.ONLINE, '1')
		check.eq (env.Properties ['System Bridge Connection'], 'Connected and authenticated')
		local came = 0
		for _, e in ipairs (eventsFired (env)) do if (e == 'Came Online') then came = came + 1 end end
		check.eq (came, 1)
	end)

	it ('BAD_TOKEN / MISSING_TOKEN errors flag the token and do NOT go online', function ()
		for _, sub in ipairs ({ 'BAD_TOKEN', 'MISSING_TOKEN' }) do
			local env = H.machine ()
			env.boot ('192.168.1.50')
			env.setProperty ('System Bridge Token', 'tk')
			env.g_ws:establish ()
			env.rx ({ type = 'ERROR', subtype = sub })
			check.falsy (env.g_online, sub)
			check.contains (env.Properties ['System Bridge Connection'], 'Invalid token')
		end
	end)

	it ('unknown error subtypes are only logged', function ()
		local env = online ()
		env.rx ({ type = 'ERROR', subtype = 'WHATEVER', message = 'meh' })
		check.truthy (env.g_online)
	end)

	it ('OPENED with a steam:// url fires Game Launched; other urls do not', function ()
		local env = online ()
		env.rx ({ type = 'OPENED', data = { url = 'steam://rungameid/620' } })
		check.deep_eq (eventsFired (env), { 'Game Launched' })
		env.reset ()
		env.rx ({ type = 'OPENED', data = { url = 'https://example.com' } })
		env.rx ({ type = 'OPENED' })
		check.deep_eq (eventsFired (env), {})
	end)

	it ('NOTIFICATION_SENT fires Notification Sent', function ()
		local env = online ()
		env.rx ({ type = 'NOTIFICATION_SENT' })
		check.deep_eq (eventsFired (env), { 'Notification Sent' })
	end)

	it ('COMMAND_COMPLETED clears the pending pad request', function ()
		local env = online ()
		env.g_pendingPad ['c4-1-COMMAND_EXECUTE'] = { cmd = 'UP', ts = os.time () }
		env.rx ({ type = 'COMMAND_COMPLETED', id = 'c4-1-COMMAND_EXECUTE', data = { exitCode = 0 } })
		check.is_nil (env.g_pendingPad ['c4-1-COMMAND_EXECUTE'])
	end)

	it ('COMMAND_NOT_FOUND for a hold degrades to a press (c4pad entry missing)', function ()
		local env = online ()
		env.Properties ['Nav Input Backend'] = 'Gamepad Bridge'
		env.ReceivedFromProxy (5001, 'START_UP', {})
		local sent = env.sent ()
		check.eq (sent [1].data.commandID, 'c4pad_hold_up')
		env.reset ()
		env.rx ({ type = 'ERROR', subtype = 'COMMAND_NOT_FOUND', id = sent [1].id })
		local after = env.sent ()
		check.eq (after [1].event, 'COMMAND_EXECUTE')
		check.eq (after [1].data.commandID, 'c4pad_press_up')
	end)

	it ('COMMAND_NOT_FOUND for a press falls back to the keyboard path', function ()
		local env = online ()
		env.Properties ['Nav Input Backend'] = 'Gamepad Bridge'
		env.ReceivedFromProxy (5001, 'ENTER', {})
		local id = env.sent () [1].id
		env.reset ()
		env.rx ({ type = 'ERROR', subtype = 'COMMAND_NOT_FOUND', id = id })
		local m = env.sent () [1]
		check.eq (m.event, 'KEYBOARD_KEYPRESS')
		check.eq (m.data.key, 'enter')
	end)

	it ('COMMAND_NOT_FOUND for an unknown id is ignored', function ()
		local env = online ()
		env.rx ({ type = 'ERROR', subtype = 'COMMAND_NOT_FOUND', id = 'nope' })
		check.eq (#env.g_ws.sent, 0)
	end)
end)

describe ('HandleModule: system', function ()
	it ('publishes uptime seconds and formatted text', function ()
		local env = online ()
		push (env, 'system', { uptime = 93784 }) -- 1d 2h 3m 4s
		check.eq (env.Variables.UPTIME_SECONDS, '93784')
		check.eq (env.Variables.UPTIME_TEXT, '1d 2h 3m')
	end)

	it ('uptime text handles zero and sub-minute values', function ()
		local env = online ()
		push (env, 'system', { uptime = 59 })
		check.eq (env.Variables.UPTIME_TEXT, '0d 0h 0m')
		push (env, 'system', { uptime = 3600 })
		check.eq (env.Variables.UPTIME_TEXT, '0d 1h 0m')
	end)

	it ('non-numeric uptime does not corrupt the numeric variable', function ()
		local env = online ()
		push (env, 'system', { uptime = 100 })
		push (env, 'system', { uptime = 'banana' })
		check.eq (env.Variables.UPTIME_SECONDS, '100')
	end)

	it ('strips control characters from the hostname', function ()
		local env = online ()
		push (env, 'system', { hostname = 'steam\r\nbox\0\t1' })
		check.eq (env.Variables.HOSTNAME, 'steam  box  1')
	end)

	it ('caps hostname length at 256 chars', function ()
		local env = online ()
		push (env, 'system', { hostname = string.rep ('A', 1000) })
		check.eq (#env.Variables.HOSTNAME, 256)
	end)

	it ('auto-fills a blank MAC property from the system module', function ()
		local env = online ()
		push (env, 'system', { mac_address = 'aa-bb-cc-dd-ee-ff' })
		check.eq (env.g_mac, 'AA:BB:CC:DD:EE:FF')
		check.eq (env.Properties ['MAC Address'], 'AA:BB:CC:DD:EE:FF')
	end)

	it ('does NOT overwrite a user-entered MAC unless Get MAC Address was requested', function ()
		local env = online ()
		env.setProperty ('MAC Address', '11:22:33:44:55:66')
		push (env, 'system', { mac_address = 'aa:bb:cc:dd:ee:ff' })
		check.eq (env.g_mac, '11:22:33:44:55:66')
		env.ExecuteCommand ('Get MAC Address')
		check.eq (env.lastSent ().event, 'GET_DATA')
		check.deep_eq (env.lastSent ().data.modules, { 'system' })
		push (env, 'system', { mac_address = 'aa:bb:cc:dd:ee:ff' })
		check.eq (env.g_mac, 'AA:BB:CC:DD:EE:FF')
		check.eq (env.g_wantMacUpdate, false)
	end)

	it ('ignores a malformed MAC from the server', function ()
		local env = online ()
		push (env, 'system', { mac_address = 'zz:zz' })
		check.eq (env.g_mac, '')
	end)

	it ('Get MAC Address while offline just explains', function ()
		local env = H.machine ()
		env.boot ('192.168.1.50')
		env.ExecuteCommand ('Get MAC Address')
		check.contains (env.Properties ['System Bridge Connection'], 'offline')
		check.eq (#env.g_ws.sent, 0)
	end)
end)

describe ('HandleModule: hardware stats', function ()
	it ('cpu temperature and usage are rounded into variables', function ()
		local env = online ()
		push (env, 'cpu', { temperature = 55.4, usage = 12.5 })
		check.eq (env.Variables.CPU_TEMPERATURE, '55')
		check.eq (env.Variables.CPU_USAGE, '13')
	end)

	it ('gpu temperature is the max across GPUs, tolerating junk entries', function ()
		local env = online ()
		push (env, 'gpus', { { temperature = 40 }, 'junk', { temperature = 71.2 }, { name = 'no temp' } })
		check.eq (env.Variables.GPU_TEMPERATURE, '71')
	end)

	it ('gpus with no usable temperature leave the variable alone', function ()
		local env = online ()
		push (env, 'gpus', { { temperature = 50 } })
		push (env, 'gpus', { { name = 'x' } })
		check.eq (env.Variables.GPU_TEMPERATURE, '50')
	end)

	it ('memory percent comes from virtual.percent', function ()
		local env = online ()
		push (env, 'memory', { virtual = { percent = 42.7 } })
		check.eq (env.Variables.MEMORY_USED_PERCENT, '43')
		push (env, 'memory', { virtual = 'oops' })
		check.eq (env.Variables.MEMORY_USED_PERCENT, '43')
	end)

	it ('battery percentage is published', function ()
		local env = online ()
		push (env, 'battery', { percentage = 88 })
		check.eq (env.Variables.BATTERY_PERCENT, '88')
	end)

	it ('string numbers from the wire are coerced', function ()
		local env = online ()
		push (env, 'cpu', { temperature = '61' })
		check.eq (env.Variables.CPU_TEMPERATURE, '61')
	end)

	it ('non-table module data and unknown modules are ignored', function ()
		local env = online ()
		push (env, 'cpu', 'oops')
		push (env, 'cpu', nil)
		push (env, 'definitely_not_a_module', { x = 1 })
		check.eq (env.Variables.CPU_TEMPERATURE, '0')
	end)
end)

describe ('HandleModule: media', function ()
	it ('builds "title - artist" and sanitizes it', function ()
		local env = online ()
		push (env, 'media', { title = 'Song\nName', artist = 'Band' })
		check.eq (env.Variables.NOW_PLAYING, 'Song Name - Band')
	end)

	it ('title alone has no dangling separator', function ()
		local env = online ()
		push (env, 'media', { title = 'Only Title' })
		check.eq (env.Variables.NOW_PLAYING, 'Only Title')
	end)

	it ('caps NOW_PLAYING at 256 chars', function ()
		local env = online ()
		push (env, 'media', { title = string.rep ('x', 500) })
		check.eq (#env.Variables.NOW_PLAYING, 256)
	end)

	it ('PLAYING fires the event and proxy NOTIFY once (deduplicated)', function ()
		local env = online ()
		push (env, 'media', { status = 'PLAYING' })
		push (env, 'media', { status = 'PLAYING' })
		check.eq (env.Variables.MEDIA_STATUS, 'PLAYING')
		check.deep_eq (eventsFired (env), { 'Media Started Playing' })
		local n = env.c4.of ('SendToProxy')
		check.eq (#n, 1)
		check.eq (n [1] [1], 5001)
		check.eq (n [1] [2], 'PLAY')
		check.eq (n [1] [4], 'NOTIFY')
	end)

	it ('PAUSED and STOPPED map to their events and notifies', function ()
		local env = online ()
		push (env, 'media', { status = 'PAUSED' })
		push (env, 'media', { status = 'STOPPED' })
		check.deep_eq (eventsFired (env), { 'Media Paused', 'Media Stopped' })
		local n = env.c4.of ('SendToProxy')
		check.eq (n [1] [2], 'PAUSE')
		check.eq (n [2] [2], 'STOP')
	end)

	it ('unknown status updates the variable but fires nothing; long status is capped', function ()
		local env = online ()
		push (env, 'media', { status = string.rep ('Z', 80) })
		check.eq (#env.Variables.MEDIA_STATUS, 32)
		check.deep_eq (eventsFired (env), {})
	end)

	it ('empty status never fires', function ()
		local env = online ()
		push (env, 'media', { title = 'x' })
		check.deep_eq (eventsFired (env), {})
		check.eq (env.c4.count ('SendToProxy'), 0)
	end)
end)
